'use strict';
const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const path=require('node:path');
const source=fs.readFileSync(path.join(__dirname,'..','search.html'),'utf8');
const script=source.match(/<script>([\s\S]*?)<\/script>/);
assert.ok(script,'inline search script missing');
new Function(script[1]);
const global={URL,console,document:{getElementById:()=>null}};
vm.runInNewContext(script[1]+'\nglobalThis.__test={safeUrl,apiOrigin,resultType,videoInfo,thumbnail,identity,parsePayload,parseInput,clock,timeText};',global);
const a=global.__test;
assert.equal(a.safeUrl('javascript:alert(1)'),null);
assert.equal(a.apiOrigin('http://127.0.0.1:7000'),'http://127.0.0.1:7000');
assert.throws(()=>a.apiOrigin('http://host:7000/a'));
assert.equal(a.resultType({classification:{content_type:'video'}}),'video');
assert.equal(a.resultType({url:'https://docs.python.org/3/tutorial'}),'text');
assert.equal(a.resultType({type:'image',image:{url:'https://example.org/img.png'}}),'image');
assert.equal(a.thumbnail({url:'https://www.youtube.com/watch?v=ABCDEFGHIJK'}),'https://i.ytimg.com/vi/ABCDEFGHIJK/hqdefault.jpg');
assert.equal(a.videoInfo({title:'Course 1080p'}).seconds,null);
assert.equal(a.videoInfo({title:'Course 1080p'}).provenance,'عنوان (تأییدنشده)');
assert.equal(a.videoInfo({duration_seconds:3600,video:{height:720}}).seconds,3600);
assert.equal(a.clock('1:15:05'),4505);
assert.equal(a.clock('3:99'),null);
assert.equal(a.timeText(3600),'1:00:00');
const one={engine:'google',type:'image',image:{url:'https://example.org/one.png'},source:{page_url:'https://example.org/p'}};
const two={engine:'google',type:'image',image:{url:'https://example.org/two.png'},source:{page_url:'https://example.org/p'}};
assert.notEqual(a.identity(one,'batch-1'),a.identity(two,'batch-1'));
const envelope={results:[{title:'A',url:'https://example.org/a'}],meta:{engines_failed:[]}};
assert.equal(a.parseInput(JSON.stringify(envelope)).responses.length,1);
assert.equal(a.parseInput('shell$ '+JSON.stringify(envelope)+'\nuser@host$').responses.length,1);
const merged={schema:'openserp.batch-merged.v1',items:[{index:1,response:envelope},{index:2,response:envelope}]};
assert.equal(a.parsePayload(merged).responses.length,2);
assert.equal(a.parsePayload({schema:'openserp.ui-snapshot.v1',responses:[envelope]}).responses.length,1);
assert.throws(()=>a.parsePayload({error:'invalid'}));
console.log('PASS search.html 19 focused parser/classification/thumbnail/metadata/security checks');
